"""§4NV: regenerate the log-title table in docs/reference/reliability/logging.html from the source.

Every literal `pretty_log` title (incl. the `_safe_pretty_log` / `_plog`
wrappers), with the icon(s) and level(s) its call sites use. Run after adding
or renaming a log line:  python scripts/gen_log_titles.py   (--check: exit 1
when the doc is stale — tests/test_4nv_log_lines.py runs it).
"""
import ast
import html
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "ghost_agent"
DOC = ROOT / "docs" / "reference" / "reliability" / "logging.html"
BEGIN = "<!-- LOG-TITLES:BEGIN (generated by scripts/gen_log_titles.py — do not edit) -->"
END = "<!-- LOG-TITLES:END -->"
_FUNCS = {"pretty_log", "_safe_pretty_log", "_plog"}


def _icons() -> dict:
    sys.path.insert(0, str(ROOT / "src"))
    from ghost_agent.utils.logging import Icons
    return {k: v for k, v in vars(Icons).items() if k.isupper()}


def collect() -> dict:
    icons = _icons()
    rows = defaultdict(lambda: {"icons": set(), "levels": set(), "files": set()})
    for f in sorted(SRC.rglob("*.py")):
        try:
            tree = ast.parse(f.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        for n in ast.walk(tree):
            if not isinstance(n, ast.Call) or not n.args:
                continue
            name = getattr(n.func, "id", None) or getattr(n.func, "attr", None)
            if name not in _FUNCS:
                continue
            t = n.args[0]
            if not (isinstance(t, ast.Constant) and isinstance(t.value, str)):
                continue
            r = rows[t.value.lower()]
            r["files"].add(str(f.relative_to(SRC)))
            kw = {k.arg: k.value for k in n.keywords if k.arg}
            ic = kw.get("icon")
            if isinstance(ic, ast.Attribute) and ic.attr in icons:
                r["icons"].add(icons[ic.attr])
            elif ic is not None and not isinstance(ic, ast.Constant):
                r["icons"].add("(varies)")
            lv = kw.get("level")
            r["levels"].add(lv.value if isinstance(lv, ast.Constant) else ("(varies)" if lv is not None else "INFO"))
    return rows


def render(rows: dict) -> str:
    out = [BEGIN,
           f'  <h2 id="titles">Every log title <span class="tag">generated · {len(rows)} titles</span></h2>',
           "  <p>Each literal title the code can print, as it appears in the stream (lower-cased), with the icon(s) "
           "and level(s) its call sites use. Titles built at run time (e.g. <code>Verify depth</code>, "
           "<code>Recovery Plan #N</code>) are not listed. Regenerate with <code>python scripts/gen_log_titles.py</code>.</p>",
           "  <div class=\"scroll\"><table>", "    <tr><th>Title</th><th>Icon</th><th>Level</th><th>Where</th></tr>"]
    for title in sorted(rows):
        r = rows[title]
        out.append("    <tr><td><code>{}</code></td><td>{}</td><td>{}</td><td>{}</td></tr>".format(
            html.escape(title), " ".join(sorted(r["icons"])) or "🔹",
            ", ".join(sorted(r["levels"])), html.escape(", ".join(sorted(r["files"])))))
    out += ["  </table></div>", END]
    return "\n".join(out)


def main(check: bool = False) -> int:
    doc = DOC.read_text(encoding="utf-8")
    block = render(collect())
    if BEGIN in doc and END in doc:
        new = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    else:
        new = doc.replace("</main>", block + "\n</main>", 1)
    if check:
        return 0 if new == doc else 1
    DOC.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
